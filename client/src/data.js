const roundTo = (value, step) => Math.round(value / step) * step;

export function maxRentFor(originalPrice) {
  return Math.max(MIN_RENT, roundTo(originalPrice * MAX_RENT_SHARE, 10));
}

export function suggestedRentFor(originalPrice) {
  return Math.max(MIN_RENT, roundTo(originalPrice * 0.025, 10));
}

export function depositFor(originalPrice) {
  return Math.max(MIN_DEPOSIT, roundTo(originalPrice * DEPOSIT_SHARE, 100));
}

export function getCategory(id) {
  return categories.find((category) => category.id === id);
}

export function getClub(id) {
  return clubs.find((club) => club.id === Number(id));
}

export function formatRupees(amount) {
  return `₹${Number(amount).toLocaleString("en-IN")}`;
}

export function formatPrice(pricePerDay) {
  return `${formatRupees(pricePerDay)}/day`;
}

export function toISODate(date) {
  const local = new Date(date.getTime() - date.getTimezoneOffset() * 60000);
  return local.toISOString().slice(0, 10);
}

export function ownerLabel(item) {
  const club = getClub(item.clubId);
  return club ? `${club.name} club` : item.ownerName;
}
